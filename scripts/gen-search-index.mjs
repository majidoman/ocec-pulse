// Builds src/lib/search-index.gen.ts: every page title, section heading and field label
// under /insights and /settings, in English and Arabic, for the menu search box.
// Run: node scripts/gen-search-index.mjs (also runs before every build).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const i18n = readFileSync(join(root, "src/lib/i18n.ts"), "utf8");
const arStart = i18n.indexOf("\n  ar: {");
const dict = (block) => {
  const out = {};
  for (const m of block.matchAll(/^\s{4}(\w+):\s*"((?:[^"\\]|\\.)*)",?\s*$/gm)) out[m[1]] = m[2];
  return out;
};
const EN = dict(i18n.slice(0, arStart));
const AR = dict(i18n.slice(arStart));
const clean = (s) => (s ?? "").replace(/\\"/g, '"').replace(/\{[^}]*\}/g, "").replace(/\s+/g, " ").replace(/^[\s·:–-]+|[\s·:–-]+$/g, "").trim();

const EXPR = String.raw`(?:t\("(\w+)"\)|loc\(\{\s*en:\s*"((?:[^"\\]|\\.)*)",\s*ar:\s*"((?:[^"\\]|\\.)*)"\s*\}\))`;
const PATTERNS = [
  ["page", new RegExp(String.raw`<PageFrame[\s\S]{0,80}?title=\{` + EXPR, "g")],
  ["section", new RegExp(String.raw`<(?:h[1-4]|CardTitle|Label)\b[^>]*>\s*\{` + EXPR, "g")],
  ["field", new RegExp(String.raw`\blabel=\{` + EXPR, "g")],
];

const entries = [];
const seen = new Set();
for (const area of ["insights", "settings"]) {
  const dir = join(root, "src/routes", area);
  for (const file of readdirSync(dir).filter((f) => f.endsWith(".tsx") && f !== "route.tsx").sort()) {
    const src = readFileSync(join(dir, file), "utf8");
    const name = file.replace(/\.tsx$/, "");
    let to = name === "index" ? `/${area}` : `/${area}/${name}`;
    let hash;
    const r = src.match(/redirect\(\{\s*to:\s*"([^"]+)"(?:,\s*hash:\s*"([^"]+)")?/);
    if (r) [to, hash] = [r[1], r[2]];
    for (const [kind, re] of PATTERNS) {
      for (const m of src.matchAll(re)) {
        const en = clean(m[1] ? EN[m[1]] : m[2]);
        const ar = clean(m[1] ? AR[m[1]] : m[3]);
        if (!en || !ar) continue;
        // A merged page's own title becomes a section of the page it now lives in.
        const k = r && kind === "page" ? "section" : kind;
        const id = `${to}#${hash ?? ""}|${en}`;
        if (seen.has(id)) continue;
        seen.add(id);
        entries.push({ to, ...(hash ? { hash } : {}), kind: k, en, ar });
      }
    }
  }
}

const body = `// Generated by scripts/gen-search-index.mjs — do not edit by hand.
export type SearchEntry = { to: string; hash?: string; kind: "page" | "section" | "field"; en: string; ar: string };
export const SEARCH_INDEX: SearchEntry[] = ${JSON.stringify(entries, null, 1)};
`;
writeFileSync(join(root, "src/lib/search-index.gen.ts"), body);
console.log(`search index: ${entries.length} entries`);
